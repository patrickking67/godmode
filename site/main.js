/* Godmode landing site behavior.
   No framework, no bundler, no CDN. Fetches ./data/godmode.json (generated by the plugin
   build) and upgrades the static fallback markup into the interactive catalog. If the
   fetch fails, the static markup stays and the page still reads correctly. */

(function () {
  "use strict";

  var REPO = "https://github.com/patrickking67/godmode";

  function el(tag, className, text) {
    var node = document.createElement(tag);
    if (className) node.className = className;
    if (text != null) node.textContent = text;
    return node;
  }

  /* ---------- Workflow browser (vertical tabs, WAI-ARIA tabs pattern) ---------- */

  function workflowPanel(cmd) {
    var panel = el("div", "wf-detail");
    panel.id = "wf-panel";
    panel.setAttribute("role", "tabpanel");
    panel.setAttribute("aria-labelledby", "wf-tab-" + cmd.name);
    panel.tabIndex = 0;

    var title = el("h3");
    title.appendChild(el("span", "slash", "/"));
    title.appendChild(document.createTextNode("godmode:" + cmd.name));
    panel.appendChild(title);
    panel.appendChild(el("p", "wf-desc", cmd.description));
    panel.appendChild(
      el(
        "p",
        "wf-run",
        cmd.invocation === "manual"
          ? "Runs only when you ask for it by name. Neither engine starts it on its own."
          : "Run it by name, or let the agent pick it when your request matches.",
      ),
    );

    var facts = el("div", "wf-facts");
    var stepsBox = el("div");
    stepsBox.appendChild(el("h4", null, "Procedure"));
    var steps = el("ol", "wf-steps");
    cmd.steps.forEach(function (step) {
      steps.appendChild(el("li", null, step));
    });
    stepsBox.appendChild(steps);
    facts.appendChild(stepsBox);

    var toolsBox = el("div");
    toolsBox.appendChild(el("h4", null, "Pre-approved in Claude Code"));
    var tools = el("ul", "wf-tools");
    cmd.allowedTools.forEach(function (tool) {
      tools.appendChild(el("li", null, tool));
    });
    toolsBox.appendChild(tools);
    toolsBox.appendChild(
      el("p", "wf-run", "Everything else goes through your normal permission prompts."),
    );
    facts.appendChild(toolsBox);
    panel.appendChild(facts);

    var details = el("details", "wf-body");
    details.appendChild(el("summary", null, "Read the full instructions"));
    var pre = el("pre");
    pre.tabIndex = 0;
    pre.appendChild(el("code", null, cmd.body));
    details.appendChild(pre);
    var link = el("a", null, "View the source file on GitHub");
    link.href = REPO + "/blob/main/" + cmd.source;
    link.rel = "noopener";
    var linkLine = el("p", "note");
    linkLine.appendChild(link);
    details.appendChild(linkLine);
    panel.appendChild(details);
    return panel;
  }

  function renderWorkflows(root, data) {
    var commands = data.commands;
    var browser = el("div", "wf-browser");
    var list = el("div", "wf-list");
    list.setAttribute("role", "tablist");
    list.setAttribute("aria-orientation", "vertical");
    list.setAttribute("aria-label", "Workflows");
    var tabs = [];

    function select(tab, focus) {
      tabs.forEach(function (t) {
        var on = t === tab;
        t.setAttribute("aria-selected", on ? "true" : "false");
        t.tabIndex = on ? 0 : -1;
      });
      var cmd = commands.filter(function (c) {
        return c.name === tab.getAttribute("data-name");
      })[0];
      var old = browser.querySelector(".wf-detail");
      var next = workflowPanel(cmd);
      if (old) browser.replaceChild(next, old);
      else browser.appendChild(next);
      if (focus) tab.focus();
    }

    (data.pillars || []).forEach(function (pillar) {
      var group = commands.filter(function (c) {
        return c.pillar === pillar;
      });
      if (!group.length) return;
      // A tablist may own only tabs, so the group heading is presentational and each tab
      // points at it as its description instead.
      var heading = el("p", "wf-group-title", pillar);
      heading.id = "wf-group-" + pillar.toLowerCase().replace(/[^a-z0-9]+/g, "-");
      heading.setAttribute("role", "presentation");
      list.appendChild(heading);
      group.forEach(function (cmd) {
        var tab = el("button", "wf-tab", cmd.name);
        tab.type = "button";
        tab.id = "wf-tab-" + cmd.name;
        tab.setAttribute("role", "tab");
        tab.setAttribute("aria-controls", "wf-panel");
        tab.setAttribute("aria-describedby", heading.id);
        tab.setAttribute("data-name", cmd.name);
        tab.addEventListener("click", function () {
          select(tab, false);
        });
        tabs.push(tab);
        list.appendChild(tab);
      });
    });

    list.addEventListener("keydown", function (event) {
      var index = tabs.indexOf(document.activeElement);
      if (index < 0) return;
      var next = null;
      if (event.key === "ArrowDown" || event.key === "ArrowRight") {
        next = tabs[(index + 1) % tabs.length];
      } else if (event.key === "ArrowUp" || event.key === "ArrowLeft") {
        next = tabs[(index - 1 + tabs.length) % tabs.length];
      } else if (event.key === "Home") next = tabs[0];
      else if (event.key === "End") next = tabs[tabs.length - 1];
      if (!next) return;
      event.preventDefault();
      select(next, true);
    });

    if (!tabs.length) return;
    browser.appendChild(list);
    root.replaceChildren(browser);
    root.removeAttribute("data-fallback");
    select(tabs[0], false);
  }

  /* ---------- Servers table ---------- */

  function renderServers(root, connectors) {
    var body = root.querySelector("tbody");
    if (!body) return;
    var frag = document.createDocumentFragment();
    connectors.forEach(function (c) {
      var row = el("tr");
      var name = el("th");
      name.scope = "row";
      var link = el("a", null, c.title);
      link.href = c.homepage;
      link.rel = "noopener";
      name.appendChild(link);
      name.appendChild(el("span", "srv-blurb", c.blurb));
      row.appendChild(name);
      row.appendChild(
        el("td", "kind", c.category + ", " + (c.transport === "http" ? "HTTPS" : "npx")),
      );
      var cell = el("td");
      cell.appendChild(el("code", null, c.endpoint));
      row.appendChild(cell);
      frag.appendChild(row);
    });
    body.replaceChildren(frag);
    root.removeAttribute("data-fallback");
  }

  /* ---------- Subagents, hooks, roadmap ---------- */

  function renderList(root, items, toParts) {
    var frag = document.createDocumentFragment();
    items.forEach(function (item) {
      var parts = toParts(item);
      var li = el("li");
      li.appendChild(el("strong", null, parts[0]));
      var text = el("span", null, parts[1]);
      if (parts[2]) text.appendChild(el("span", "tag", parts[2]));
      li.appendChild(text);
      frag.appendChild(li);
    });
    root.replaceChildren(frag);
    root.removeAttribute("data-fallback");
  }

  function loadData() {
    fetch("./data/godmode.json", { cache: "no-cache" })
      .then(function (res) {
        if (!res.ok) throw new Error("HTTP " + res.status);
        return res.json();
      })
      .then(function (data) {
        var byId = function (id) {
          return document.getElementById(id);
        };
        if (byId("commands-root") && Array.isArray(data.commands)) {
          renderWorkflows(byId("commands-root"), data);
        }
        if (byId("connectors-root") && Array.isArray(data.connectors)) {
          renderServers(byId("connectors-root"), data.connectors);
        }
        if (byId("agents-root") && Array.isArray(data.agents)) {
          renderList(byId("agents-root"), data.agents, function (a) {
            return [a.name, a.role, a.tools.join(", ")];
          });
        }
        if (byId("hooks-root") && Array.isArray(data.hooks)) {
          renderList(byId("hooks-root"), data.hooks, function (h) {
            return [h.event, h.detail, h.script];
          });
        }
        if (byId("roadmap-root") && Array.isArray(data.roadmap)) {
          renderList(byId("roadmap-root"), data.roadmap, function (r) {
            return [r.phase, r.items.join(". ") + "."];
          });
        }
      })
      .catch(function (err) {
        if (window.console && console.warn) {
          console.warn("Godmode: catalog did not load, showing the static page.", err);
        }
      });
  }

  /* ---------- Nav toggle ---------- */

  function initNav() {
    var toggle = document.querySelector(".nav-toggle");
    var links = document.getElementById("nav-links");
    if (!toggle || !links) return;

    function setOpen(open) {
      toggle.setAttribute("aria-expanded", open ? "true" : "false");
      toggle.setAttribute("aria-label", open ? "Close menu" : "Open menu");
      links.classList.toggle("is-open", open);
    }
    toggle.addEventListener("click", function () {
      setOpen(toggle.getAttribute("aria-expanded") !== "true");
    });
    links.addEventListener("click", function (event) {
      if (event.target.closest("a")) setOpen(false);
    });
    document.addEventListener("keydown", function (event) {
      if (event.key === "Escape" && toggle.getAttribute("aria-expanded") === "true") {
        setOpen(false);
        toggle.focus();
      }
    });
  }

  /* ---------- Theme toggle ----------
     The inline script in index.html applies a stored choice before the first paint. With
     no stored choice the page follows the system setting through CSS alone. */

  var THEME_KEY = "godmode-theme";
  var THEME_COLOR = { dark: "#0a0a0f", light: "#f7f6fb" };

  function systemTheme() {
    return window.matchMedia && window.matchMedia("(prefers-color-scheme: light)").matches
      ? "light"
      : "dark";
  }

  function activeTheme() {
    var chosen = document.documentElement.getAttribute("data-theme");
    return chosen === "light" || chosen === "dark" ? chosen : systemTheme();
  }

  function initTheme() {
    var toggle = document.querySelector(".theme-toggle");
    if (!toggle) return;

    function describe() {
      var label = "Switch to " + (activeTheme() === "light" ? "dark" : "light") + " theme";
      toggle.setAttribute("aria-label", label);
      toggle.title = label;
    }

    toggle.addEventListener("click", function () {
      var next = activeTheme() === "light" ? "dark" : "light";
      document.documentElement.setAttribute("data-theme", next);
      Array.prototype.forEach.call(
        document.querySelectorAll('meta[name="theme-color"]'),
        function (meta) {
          meta.setAttribute("content", THEME_COLOR[next]);
        },
      );
      try {
        window.localStorage.setItem(THEME_KEY, next);
      } catch (e) {
        /* Storage is blocked: the choice lasts for this page view only. */
      }
      describe();
    });

    if (window.matchMedia) {
      var query = window.matchMedia("(prefers-color-scheme: light)");
      if (query.addEventListener) query.addEventListener("change", describe);
      else if (query.addListener) query.addListener(describe);
    }
    describe();
  }

  /* ---------- Copy buttons ---------- */

  function initCopy() {
    Array.prototype.forEach.call(document.querySelectorAll(".copy-btn"), function (btn) {
      var label = btn.querySelector(".copy-label") || btn;
      var resetTimer = 0;

      function show(message, ok) {
        label.textContent = message;
        btn.classList.toggle("is-copied", ok);
        // A second click restarts the wait, so an earlier timer cannot cut the message short.
        window.clearTimeout(resetTimer);
        resetTimer = window.setTimeout(function () {
          label.textContent = "Copy";
          btn.classList.remove("is-copied");
        }, 1800);
      }

      /* For pages without the async Clipboard API (plain http, older browsers) and for a
         refused permission. The textarea is fixed in the viewport so selecting it does not
         scroll the page, and focus goes back to the button afterwards. */
      function fallback(text) {
        var ta = document.createElement("textarea");
        ta.value = text;
        ta.setAttribute("readonly", "");
        ta.setAttribute("aria-hidden", "true");
        ta.tabIndex = -1;
        ta.style.position = "fixed";
        ta.style.top = "0";
        ta.style.left = "0";
        ta.style.opacity = "0";
        document.body.appendChild(ta);
        ta.focus({ preventScroll: true });
        ta.select();
        var ok = false;
        try {
          ok = document.execCommand("copy");
        } catch (e) {
          ok = false;
        }
        document.body.removeChild(ta);
        btn.focus({ preventScroll: true });
        show(ok ? "Copied" : "Select and copy", ok);
      }

      btn.addEventListener("click", function () {
        var text = btn.getAttribute("data-copy") || "";
        if (navigator.clipboard && navigator.clipboard.writeText) {
          navigator.clipboard.writeText(text).then(
            function () {
              show("Copied", true);
            },
            function () {
              fallback(text);
            },
          );
        } else {
          fallback(text);
        }
      });
    });
  }

  function revealHero() {
    Array.prototype.forEach.call(document.querySelectorAll(".hero .reveal"), function (node) {
      node.classList.add("is-visible");
    });
  }

  function init() {
    initNav();
    initTheme();
    initCopy();
    revealHero();
    loadData();
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
})();
